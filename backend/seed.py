def get_or_create_user(name, email, role, password):
    user = User.query.filter_by(email=email).first()
    if not user:
        user = User(name=name, email=email, role=role, password=hash_password(password))
        db.session.add(user)
        db.session.flush()
    return user


def seed():
    password = os.environ.get('DEMO_PASSWORD', 'password123')
    existing = {name for (name,) in db.session.query(FoodItem.name)}
    new_foods = [FoodItem(**f) for f in SAMPLE_FOODS + DINNER_FOODS if f['name'] not in existing]
    db.session.add_all(new_foods)

    dietitian = get_or_create_user('Dr. Kavya Rao', 'dietitian@ayuaahar.com', 'dietitian', password)
    patient_user = get_or_create_user('Aarav Mehta', 'patient@ayuaahar.com', 'patient', password)

    created = []
    if Patient.query.filter_by(user_id=dietitian.id).count() == 0:
        now = datetime.utcnow()
        created = [Patient(user_id=dietitian.id, **p) for p in DEMO_PATIENTS]
        created[0].patient_user_id = patient_user.id  # the demo patient login sees this record
        for i, p in enumerate(created):
            p.created_at = now - timedelta(days=40 - i * 6)
        db.session.add_all(created)
        db.session.flush()

        base = now.replace(minute=0, second=0, microsecond=0)
        db.session.add_all(
            Appointment(
                patient_id=created[i].id,
                notes=notes,
                status=status,
                appointment_date=(base + timedelta(days=d)).replace(hour=h),
            )
            for i, d, h, notes, status in DEMO_APPOINTMENTS
        )
        db.session.add_all(
            Progress(patient_id=created[i].id, week_number=w, adherence_score=a, weight=wt, notes=n, symptoms=s)
            for i, rows in DEMO_PROGRESS.items()
            for w, (a, wt, n, s) in enumerate(rows, start=1)
        )
    db.session.commit()

    for p in created:
        DietPlanService.create_diet_plan(p.id, f'{p.prakriti} Balance Plan')

    print(f'Seed complete: +{len(new_foods)} foods, +{len(created)} demo patients')


if __name__ == '__main__':
    with create_app().app_context():
        seed()
